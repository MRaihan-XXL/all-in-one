test('runDoctor --fix: spawn failure → "fix failed" note, issues still reported, exit 1', async (t) => {
  mockNet(t);
  hermeticHome(t, { withBlock: true });
  fs.rmSync(MANIFEST, { force: true });
  const origExists = fs.existsSync.bind(fs);
  t.mock.method(fs, 'existsSync', (p) => (/\bbin[\\/]aio\.js$/.test(String(p)) ? false : origExists(p)));
  assert.equal(aioBinPath(), process.execPath, 'hidden bin → aioBinPath falls back to the runtime');

  const r = await runDoctor({ fix: true });

  assert.equal(r.ok, false, 'fix could not run → issues remain');
  assert.equal(r.exit, 1);
  assert.match(r.text, /fix failed: /, 'spawn error surfaced verbatim');
  assert.ok(!r.text.includes('setup re-run complete'), 'no success note on failure');
  assert.match(r.text, /run `aio doctor --fix`/, 'hint still shown');
});

test('runDoctor --fix --json: spawn failure → payload carries fix {attempted, ok:false, error}', async (t) => {
  mockNet(t);
  hermeticHome(t, { withBlock: true });
  fs.rmSync(MANIFEST, { force: true });
  const origExists = fs.existsSync.bind(fs);
  t.mock.method(fs, 'existsSync', (p) => (/\bbin[\\/]aio\.js$/.test(String(p)) ? false : origExists(p)));

  const r = await runDoctor({ fix: true, json: true });

  const p = JSON.parse(r.text);
  assert.equal(p.mode, 'fix', 'fix mode in the payload');
  assert.equal(p.fix.attempted, true, 'the fix was attempted');
  assert.equal(p.fix.ok, false, 'spawn failure → not ok');
  assert.match(String(p.fix.error), /\S/, 'the spawn error is surfaced verbatim');
  assert.equal(r.ok, false, 'issues remain after a failed fix');
  assert.equal(r.exit, 1, 'exit mirrors ok');
});

/** Spawn the real `aio --yes` setup, fully sandboxed: temp state dir (env), temp
 *  home (USERPROFILE/HOME), empty PATH (no external tools reachable). */
function sandboxChild(t, home) {
  const saved = { USERPROFILE: process.env.USERPROFILE, HOME: process.env.HOME };
  process.env.USERPROFILE = home;
  process.env.HOME = home;
  t.after(() => {
    if (saved.USERPROFILE === undefined) delete process.env.USERPROFILE;
    else process.env.USERPROFILE = saved.USERPROFILE;
    if (saved.HOME === undefined) delete process.env.HOME;
    else process.env.HOME = saved.HOME;
  });
}

test('runDoctor --fix: healthy spawn → setup re-run, after-fix report, exit 0', async (t) => {
  mockNet(t, { github: 'fail', ollama: 'fail' });
  const home = hermeticHome(t); // no block, no agent dirs → nothing to inject
  sandboxChild(t, home);
  fs.rmSync(MANIFEST, { force: true });
  fs.rmSync(CONFIG, { force: true });

  const r = await runDoctor({ fix: true });

  assert.match(r.text, /fix: setup re-run complete — re-check:/, 'child setup ran');
  assert.equal(r.ok, true, r.text);
  assert.match(r.text, /after fix: 0 issue\(s\), \d+ warning\(s\)/);
  assert.equal(r.exit, 0);
  assert.ok(fs.existsSync(MANIFEST), 'the child regenerated the manifest in the temp state dir');
});

test('runDoctor --fix --json: healthy spawn → machine payload with mode "fix"', async (t) => {
  mockNet(t, { github: 'fail', ollama: 'fail' });
  const home = hermeticHome(t);
  sandboxChild(t, home);
  fs.rmSync(MANIFEST, { force: true });
  fs.rmSync(CONFIG, { force: true });

  const r = await runDoctor({ fix: true, json: true });

  const p = JSON.parse(r.text);
  assert.equal(p.mode, 'fix', 'fix mode in the payload');
  assert.equal(p.schemaVersion, 1);
  assert.deepEqual(p.fix, { attempted: true, ok: true }, 'machine-readable fix outcome (no error key on success)');
  assert.equal(p.ok, true, `issues: ${p.issues} (${p.checks.filter((c) => c.level === 'bad').map((c) => c.detail).join('; ')})`);
  assert.equal(p.checks.length, 9, 'still exactly 9 checks after a fix');
  assert.equal(r.ok, p.ok, 'r.ok mirrors the payload');
  assert.equal(r.exit, 0, 'exit mirrors ok');
});
