function json(body) {
  return new Response(JSON.stringify(body), { status: 200, headers: { 'content-type': 'application/json' } });
}

/** Probe control: github / ollama answer or fail independently; never real network. */
function mockNet(t, { github = 'ok', ollama = 'ok' } = {}) {
  return t.mock.method(globalThis, 'fetch', async (input) => {
    const url = String(input instanceof Request ? input.url : input);
    if (url.includes('api.github.com')) {
      if (github === 'ok') return json({ resources: {} });
      throw new Error('connect ECONNREFUSED 140.82.112.9:443');
    }
    if (url.includes('/api/tags')) {
      if (ollama === 'ok') return json({ models: [{ name: 'qwen3:4b' }] });
      throw new Error('connect ECONNREFUSED 127.0.0.1:11434');
    }
    throw new Error(`unexpected network call in test: ${url}`);
  });
}

/** Temp home + inert PATH/APPDATA: detectAgents/blockTargets never see the real machine. */
function hermeticHome(t, { withBlock = false, withClaudeDir = false } = {}) {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'aio-doctor-cov-home-'));
  if (withBlock) fs.writeFileSync(path.join(home, 'AGENTS.md'), `${BLOCK_START}\nmocked\n${BLOCK_END}\n`);
  if (withClaudeDir) fs.mkdirSync(path.join(home, '.claude'), { recursive: true }); // dir without CLAUDE.md
  const saved = { PATH: process.env.PATH, APPDATA: process.env.APPDATA };
  process.env.PATH = '';
  process.env.APPDATA = path.join(home, 'AppData', 'Roaming'); // absent → zed target dropped
  t.mock.method(os, 'homedir', () => home);
  t.after(() => {
    if (saved.PATH === undefined) delete process.env.PATH;
    else process.env.PATH = saved.PATH;
    if (saved.APPDATA === undefined) delete process.env.APPDATA;
    else process.env.APPDATA = saved.APPDATA;
    fs.rmSync(home, { recursive: true, force: true });
  });
  return home;
}

function check(r, id) {
  const c = r.checks.find((x) => x.id === id);
  assert.ok(c, `check "${id}" present in ${r.checks.map((x) => x.id).join(', ')}`);
  return c;
}

/* ---------------- node version lanes (lines 66–74) ---------------- */

test('runChecks: unsupported node majors → warn (18+) and bad (<18), supported restores', async (t) => {
  mockNet(t);
  hermeticHome(t);
  fs.rmSync(MANIFEST, { force: true });
  const desc = Object.getOwnPropertyDescriptor(process.versions, 'node');
  t.after(() => Object.defineProperty(process.versions, 'node', desc));

  Object.defineProperty(process.versions, 'node', { value: '20.10.0', configurable: true, enumerable: true });
  const warnR = await runChecks({});
  const warn = check(warnR, 'node');
  assert.equal(warn.level, 'warn', 'node 20 runs but is unsupported');
  assert.match(warn.detail, /runs, but unsupported; install Node >= 22/);

  Object.defineProperty(process.versions, 'node', { value: '16.0.0', configurable: true, enumerable: true });
  const badR = await runChecks({});
  const bad = check(badR, 'node');
  assert.equal(bad.level, 'bad', 'node < 18 is a hard fail');
  assert.match(bad.detail, /Node >= 22 required/);
  assert.equal(badR.ok, false, 'a bad node line fails the run');
});

