test('runChecks: ledger broken entries (missing/gone/jsonc/toml/parse) → joined warn; valid → ok', async (t) => {
  mockNet(t);
  hermeticHome(t, { withBlock: true });
  fs.writeFileSync(MANIFEST, FRESH_MANIFEST);
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'aio-ledger-fix-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const KEY = 'codebase-memory-mcp';
  const goneJsonc = path.join(dir, 'opencode.jsonc');
  const goneToml = path.join(dir, 'config.toml');
  const parseBad = path.join(dir, 'broken.json');
  const entryGone = path.join(dir, 'entry.json');
  const valid = path.join(dir, 'ok.json');
  fs.writeFileSync(goneJsonc, '{ "mcp": {} }');
  fs.writeFileSync(goneToml, 'model = "g"\n');
  fs.writeFileSync(parseBad, '{ not json');
  fs.writeFileSync(entryGone, JSON.stringify({ other: 1 }));
  fs.writeFileSync(valid, JSON.stringify({ mcpServers: { [KEY]: { command: 'x' } } }));
  const missing = path.join(dir, 'missing.json'); // never created

  fs.writeFileSync(
    LEDGER,
    JSON.stringify(
      [
        { file: missing, key: KEY },
        { file: goneJsonc, key: KEY },
        { file: goneToml, key: KEY },
        { file: parseBad, key: KEY },
        { file: entryGone, key: KEY },
        { file: valid, key: KEY },
      ],
      null,
      2
    )
  );

  const broken = await runChecks({});
  const ledger = check(broken, 'mcp ledger');
  assert.equal(ledger.level, 'warn');
  assert.match(ledger.detail, /codebase-memory-mcp: missing\.json missing/, 'missing file reported');
  assert.match(ledger.detail, /entry gone from opencode\.jsonc/, 'jsonc text check');
  assert.match(ledger.detail, /entry gone from config\.toml/, 'toml text check');
  assert.match(ledger.detail, /broken\.json: parse error — fix before `aio rollback`/, 'unparseable json');
  assert.match(ledger.detail, /entry gone from entry\.json/, 'valid json without the key');
  assert.ok(!/ok\.json/.test(ledger.detail), 'the valid entry is not flagged');

  fs.writeFileSync(LEDGER, JSON.stringify([{ file: valid, key: KEY }], null, 2));
  const healthy = await runChecks({});
  const okLedger = check(healthy, 'mcp ledger');
  assert.equal(okLedger.level, 'ok');
  assert.match(okLedger.detail, /1 aio-added MCP entry file\(s\) present & valid/);

  fs.writeFileSync(LEDGER, '[]');
  const empty = await runChecks({});
  assert.match(check(empty, 'mcp ledger').detail, /0 entries on record — nothing aio-added/);
});

