test('blockTargets: 7 agent targets in order, every path absolute, no global by default', () => {
  const home = tempHome();
  const list = blockTargets(home, { agents: [] }); // explicit [] → globalWanted never scans the real machine

  assert.deepEqual(
    list.map((t) => t.label),
    ['opencode', 'claude', 'kimi', 'jcode', 'codex', 'gemini', 'zed'],
    'AGENT_INSTRUCTIONS order + zed, no global'
  );
  for (const t of list) {
    assert.ok(path.isAbsolute(t.file), `${t.label}: file absolute (${t.file})`);
    assert.ok(path.isAbsolute(t.dir), `${t.label}: dir absolute (${t.dir})`);
    assert.ok(t.file.startsWith(t.dir + path.sep), `${t.label}: file inside dir`);
  }
  const opencode = list.find((t) => t.label === 'opencode');
  assert.equal(opencode.file, path.join(home, '.config', 'opencode', 'AGENTS.md'));
  assert.equal(opencode.dir, path.join(home, '.config', 'opencode'));
});

test('blockTargets: global only with global:"always" or globalWanted(home, agents)', () => {
  const home = tempHome();
  assert.equal(
    blockTargets(home, { agents: [] }).some((t) => t.label === 'global'),
    false,
    'auto + no ~/AGENTS.md + no hermes/freebuff → no global'
  );

  const always = blockTargets(home, { agents: [], global: 'always' }).find((t) => t.label === 'global');
  assert.ok(always, "global:'always' → global present");
  assert.equal(always.file, path.join(home, 'AGENTS.md'));
  assert.equal(always.dir, home);

  fs.writeFileSync(path.join(home, 'AGENTS.md'), '# rules\n');
  const auto = blockTargets(home, { agents: [] }).filter((t) => t.label === 'global');
  assert.equal(auto.length, 1, 'existing ~/AGENTS.md → exactly one global entry');

  const home2 = tempHome();
  assert.ok(blockTargets(home2, { agents: [{ name: 'hermes', found: true }] }).some((t) => t.label === 'global'));
  assert.ok(blockTargets(home2, { agents: [{ name: 'freebuff', found: true }] }).some((t) => t.label === 'global'));
  assert.equal(
    blockTargets(home2, { agents: [{ name: 'opencode', found: true }] }).some((t) => t.label === 'global'),
    false,
    'a non-hermes/freebuff agent does not pull in global'
  );
});

test('globalWanted: true on existing ~/AGENTS.md or found hermes/freebuff, else false', () => {
  const home = tempHome();
  assert.equal(globalWanted(home, []), false, 'no file + no hermes/freebuff');

  fs.writeFileSync(path.join(home, 'AGENTS.md'), '# rules\n');
  assert.equal(globalWanted(home, []), true, 'AGENTS.md exists');

  const bare = tempHome();
  assert.equal(globalWanted(bare, [{ name: 'hermes', found: true }]), true);
  assert.equal(globalWanted(bare, [{ name: 'freebuff', found: true }]), true);
  assert.equal(globalWanted(bare, [{ name: 'hermes', found: false }]), false, 'detected-but-absent ≠ found');
  assert.equal(globalWanted(bare, [{ name: 'claude', found: true }]), false);
});

test('zedTarget: platform branch — win32 %APPDATA%\\Zed, posix ~/.config/zed', () => {
  const home = tempHome();
  const z = zedTarget(home);
  assert.equal(z.label, 'zed');
  if (process.platform === 'win32') {
    const dir = path.join(process.env.APPDATA || path.join(home, 'AppData', 'Roaming'), 'Zed');
    assert.equal(z.dir, dir, 'win32 dir = %APPDATA%\\Zed (fallback home\\AppData\\Roaming\\Zed)');
  } else {
    assert.equal(z.dir, path.join(home, '.config', 'zed'));
  }
  assert.equal(z.file, path.join(z.dir, 'AGENTS.md'));
  assert.ok(path.isAbsolute(z.dir) && path.isAbsolute(z.file));
});

/* ---------------- 3. src/write.js drift detection (C-02) ---------------- */

test('blockEdited: false right after injectBlock, true after hand-edit inside markers', () => {
  const file = fixture('aio-v150-drift-', 'AGENTS.md', '# my rules\n');
  assert.equal(injectBlock(file, 'BODY-v1', 'drift').status, 'injected');
  assert.equal(blockEdited(file), false, 'just written → no drift');

  handEdit(file, 'BODY-v1', 'BODY-v1 + my tweak');
  assert.equal(blockEdited(file), true, 'content inside markers changed → drift');
  assert.ok(fs.readFileSync(file, 'utf8').includes('my tweak'), 'hand edit persisted');
});

test('injectBlock dry on hand-edited file → would update (hand-edit detected), writes nothing', () => {
  const file = fixture('aio-v150-drydrift-', 'AGENTS.md', '# my rules\n');
  injectBlock(file, 'BODY', 't');
  handEdit(file, 'BODY', 'BODY hacked');
  const before = fs.readFileSync(file, 'utf8');
  const n0 = backupCount();

  const r = injectBlock(file, 'BODY v2', 't', { dry: true });

  assert.match(r.status, /would update \(hand-edit detected\)/);
  assert.equal(fs.readFileSync(file, 'utf8'), before, 'dry run leaves the hand edit untouched');
  assert.equal(backupCount(), n0, 'no backup on dry run');
  assert.equal(blockEdited(file), true, 'drift still reported');
});

test('injectBlock real on hand-edited file → hand-edit replaced, backup kept, drift cleared', () => {
  const file = fixture('aio-v150-replace-', 'AGENTS.md', '# my rules\n');
  injectBlock(file, 'BODY-v1', 't');
  handEdit(file, 'BODY-v1', 'BODY-v1 hacked');
  const n0 = backupCount();

  const r = injectBlock(file, 'BODY-v2', 't');

  assert.match(r.status, /hand-edit replaced/);
  assert.match(r.status, /kept in backups\//);
  assert.equal(backupCount(), n0 + 1, 'hand-edited version kept in backups/ first');
  assert.ok(fs.readFileSync(file, 'utf8').includes('BODY-v2'), 'fresh block landed');
  assert.equal(blockEdited(file), false, 'hash refreshed → drift cleared');
});

test('stripBlock: prunes the stored hash — block gone, blockEdited false', () => {
  const file = fixture('aio-v150-strip-', 'AGENTS.md', '# my rules\n');
  injectBlock(file, 'BODY', 't');
  handEdit(file, 'BODY', 'BODY hacked');
  assert.equal(blockEdited(file), true, 'precondition: drifted');

  assert.equal(stripBlock(file), 'removed');

  assert.equal(currentBlock(file), null, 'block gone from the file');
  assert.equal(blockEdited(file), false, 'no block → no drift');
  const stored = JSON.parse(fs.readFileSync(path.join(STATE_DIR, 'block-hashes.json'), 'utf8'));
  assert.equal(stored[path.resolve(file)], undefined, 'stale drift entry pruned from block-hashes.json');
});

