/* ---------------- 5. src/status.js — hand-edit reporting (C-02) ---------------- */

test('runStatus: hand-edited block → issue "edited by hand", ok=false', (t) => {
  t.mock.method(console, 'log', () => {}); // keep test output clean
  fs.writeFileSync(path.join(STATE_DIR, 'aio-context.md'), SLIM_MANIFEST); // fresh manifest → not an issue

  const home = tempHome();
  const file = path.join(home, '.config', 'opencode', 'AGENTS.md');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  assert.equal(injectBlock(file, 'BODY-v1', 'status-drift').status, 'injected');
  t.mock.method(os, 'homedir', () => home); // runStatus scans the temp home, never the real one

  const before = runStatus({});
  assert.ok(
    !before.issues.some((i) => /edited by hand/.test(i)),
    `baseline free of drift: ${before.issues.join('; ')}`
  );

  handEdit(file, 'BODY-v1', 'BODY-v1 tweaked by user');

  const after = runStatus({});
  assert.equal(after.ok, false, `hand edit must surface: ${after.issues.join('; ')}`);
  assert.ok(
    after.issues.some((i) => /edited by hand/.test(i)),
    `expected hand-edit issue, got: ${after.issues.join('; ')}`
  );
  assert.ok(after.lines.some((l) => l.includes('injected*')), 'target line marked injected*');
  assert.ok(after.lines.some((l) => l.includes('stale')), 'stale note printed');
});

/* ---------------- 6. src/search.js — ok invariant (B-01) ---------------- */

test('runAsk: AIO_OFFLINE=1 + json → ok=false, offline message, no network', async (t) => {
  process.env.AIO_OFFLINE = '1';
  t.after(() => delete process.env.AIO_OFFLINE);
  t.mock.method(globalThis, 'fetch', async (input) => {
    throw new Error(`offline mode must not fetch: ${input}`);
  });

  const r = await runAsk({ query: 'anything', json: true });

  assert.equal(r.ok, false, 'offline → not ok');
  assert.equal(r.json, null, 'offline early-return carries no json payload');
  assert.match(r.text, /offline \(AIO_OFFLINE=1\)/);
});

test('runAsk: every source fails → sources=[] + errors present → ok=false (B-01 rule)', async (t) => {
  t.mock.method(globalThis, 'fetch', async () => {
    throw new Error('fetch failed: ECONNREFUSED');
  });

  const r = await runAsk({ query: 'csv toolkit', json: true });

  assert.equal(r.ok, false, 'empty sources + errors → ok false');
  assert.deepEqual(r.json.sources, [], 'no source answered');
  assert.ok(r.json.errors.length > 0, `failures surfaced, got: ${JSON.stringify(r.json.errors)}`);
  // the documented rule: ok = sources.length > 0 || errors.length === 0
  assert.equal(
    r.json.sources.length > 0 || r.json.errors.length === 0,
    false,
    'invariant holds for this payload'
  );
  assert.equal(r.json.count, 0);
  assert.equal(r.json.stored, 0, 'zero storage even on failure');
});

/* ---------------- 7. src/doctor.js — 9-check report ---------------- */

test('runDoctor --check: exactly 9 tagged check lines — one per expected label, in runChecks order', async (t) => {
  process.env.AIO_OFFLINE = '1';
  t.after(() => delete process.env.AIO_OFFLINE);
  t.mock.method(globalThis, 'fetch', async (input) => {
    throw new Error(`no network in doctor test: ${input}`);
  }); // offline skips github; mocked fetch makes the ollama probe fail deterministically
  fs.writeFileSync(path.join(STATE_DIR, 'aio-context.md'), SLIM_MANIFEST);

  const r = await runDoctor({ check: true });

  assert.equal(typeof r.text, 'string');
  const tagged = r.text.split('\n').filter((l) => /^\[(ok|~~|!!)\] /.test(l));
  assert.equal(tagged.length, 9, `expected exactly 9 check lines:\n${r.text}`);
  // `${tag} ${id.padEnd(14)} ${detail}` → id occupies chars 5..18 after the 4-char tag
  const ids = tagged.map((l) => l.slice(5, 19).trim());
  const expected = [
    'node',
    'state',
    'live',
    'manifest',
    'agent blocks',
    'agents',
    'gh auth',
    'ollama',
    'mcp ledger',
  ];
  assert.deepEqual([...ids].sort(), [...expected].sort(), 'exactly one line per expected label');
  assert.deepEqual(ids, expected, 'labels printed in runChecks order (one per label, none swapped/dropped)');
  assert.ok([0, 1].includes(r.exit), `exit is 0|1, got ${r.exit}`);
  assert.equal(r.exit, r.ok ? 0 : 1, 'exit mirrors ok');
});
