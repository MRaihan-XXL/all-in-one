/** Fresh temp home dir (targets/globalWanted never touch the real one). */
function tempHome() {
  return fs.mkdtempSync(path.join(os.tmpdir(), 'aio-v150-home-'));
}

/** Fresh temp fixture file with the given content. */
function fixture(prefix, name, content) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  const file = path.join(dir, name);
  fs.writeFileSync(file, content);
  return file;
}

function backupCount() {
  return fs.existsSync(BACKUP_DIR) ? fs.readdirSync(BACKUP_DIR).length : 0;
}

/** Rewrite `file` with `from` → `to` swapped INSIDE its marker block. */
function handEdit(file, from, to) {
  const txt = fs.readFileSync(file, 'utf8');
  assert.ok(txt.includes(from), `fixture contains ${from}`);
  assert.ok(
    txt.indexOf(from) > txt.indexOf(BLOCK_START) && txt.indexOf(from) < txt.indexOf(BLOCK_END),
    'edit lands inside the marker block'
  );
  fs.writeFileSync(file, txt.replace(from, to));
}

