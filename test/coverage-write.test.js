/* ---------------- backup collision (lines 19–22) ---------------- */

test('backup: millisecond-name collision → the loop picks the _1 name instead of overwriting', (t) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'aio-backup-coll-'));
  const src = path.join(dir, 'src.txt');
  fs.writeFileSync(src, 'payload');
  const origExists = fs.existsSync.bind(fs);
  let collisionReported = false;
  t.mock.method(fs, 'existsSync', (p) => {
    const s = String(p);
    // first probe of the plain millisecond-stamped dest → pretend it already
    // exists (the CI race); the _1 fallback must then be taken for real
    if (!collisionReported && /__src\.txt$/.test(s) && !/_\d+__src\.txt$/.test(s)) {
      collisionReported = true;
      return true;
    }
    return origExists(p);
  });

  const dest = backup(src, 'coll');

  assert.equal(collisionReported, true, 'collision branch exercised');
  assert.match(path.basename(dest), /^coll__.*_1__src\.txt$/, `_1 suffix chosen: ${path.basename(dest)}`);
  assert.equal(read(dest), 'payload', 'backup copy carries the original bytes');
});

/* ---------------- pruneBackups failure branches (lines 226–232) ---------------- */

test("pruneBackups: a backup that cannot be stat'ed is skipped; fresh ones stay", (t) => {
  fs.rmSync(BACKUP_DIR, { recursive: true, force: true });
  fs.mkdirSync(BACKUP_DIR, { recursive: true });
  const locked = path.join(BACKUP_DIR, 'inject__locked__a.md');
  const fresh = path.join(BACKUP_DIR, 'inject__fresh__b.md');
  fs.writeFileSync(locked, 'locked');
  fs.writeFileSync(fresh, 'fresh');
  const origStat = fs.statSync.bind(fs);
  t.mock.method(fs, 'statSync', (p) => {
    if (String(p) === locked) throw new Error('EBUSY: resource busy or locked');
    return origStat(p);
  });

  assert.equal(pruneBackups(30), 0, 'locked entry skipped, fresh one not old enough');
  assert.ok(fs.existsSync(locked), 'locked backup kept for the next run');
  assert.ok(fs.existsSync(fresh), 'fresh backup kept');
});

test('pruneBackups: no backups dir yet → 0 removed, no throw (read-only home path)', () => {
  fs.rmSync(BACKUP_DIR, { recursive: true, force: true });
  assert.equal(pruneBackups(30), 0, 'absent dir is not an error');
  assert.equal(fs.existsSync(BACKUP_DIR), false, 'prune never creates the dir');
});

