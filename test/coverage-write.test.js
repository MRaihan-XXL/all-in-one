  assert.ok(txt.includes('Live architecture — zero search storage'), 'zero-storage note');
  assert.ok(txt.includes('## AGENTS DETECTED'), 'agents section');
  assert.ok(txt.includes('- claude: found (`claude`)'), 'found agent with its binary');
  assert.ok(txt.includes('- kimi: not installed'), 'missing agent reported');
