test('ensureMcp: jsonc with a NON-empty "mcp" block → comma after the new entry; dry → plan only', (t) => {
  const home = fixtureHome(t);
  const original = '{\n  "mcp": {\n    "other-tool": { "command": "x" }\n  }\n}\n';
  const jsonc = write(path.join(home, '.config', 'opencode', 'opencode.jsonc'), original);

  const dry = ensureMcp(BIN, { dry: true });
  assert.equal(dry[0].status, 'would add (dry-run)', 'dry plan for the jsonc slot');
  assert.equal(read(jsonc), original, 'dry run writes nothing');
  assert.equal(dry[4].status, 'file not found — skipped', 'missing slots stay skipped even in dry mode');

  const real = ensureMcp(BIN);
  assert.equal(real[0].status, 'added', 'non-empty block accepts the insert');
  const j = read(jsonc);
  assert.ok(j.includes(KEY), 'entry present');
  assert.ok(/,\n\s*"other-tool"/.test(j), `comma separates entry from the next key:\n${j}`);
  assert.ok(j.includes('"other-tool": { "command": "x" }'), 'pre-existing entry kept');
});

/* ---------------- removeMcpAdditions matrix (lines 353–409) ---------------- */

test('removeMcpAdditions: missing + already-gone + toml removed + toml partial-removal keep', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'aio-rm-mcp-a-'));
  const missing = path.join(dir, 'missing.json'); // never created
  const gone = write(path.join(dir, 'gone.json'), JSON.stringify({ mcpServers: { other: 1 } }, null, 2));
  const okToml = write(
    path.join(dir, 'ok.toml'),
    `model = "g"\n\n[mcp_servers.${KEY}]\n# added by aio — remove via \`aio rollback\`\ncommand = "x"\n`
  );
  const badToml = write(
    path.join(dir, 'bad.toml'),
    `[mcp_servers.${KEY}]\ncommand = "x"\n[.note]\n${KEY} must stay visible\n`
  );
  putLedger([
    { file: missing, key: KEY },
    { file: gone, key: KEY },
    { file: okToml, key: KEY },
    { file: badToml, key: KEY },
  ]);

  const out = removeMcpAdditions();

  assert.deepEqual(
    out.map((o) => o.status),
    [
      'missing — ledger entry kept for retry',
      'already gone',
      'removed',
      'unsupported layout — manual removal needed, ledger entry kept',
    ],
    `per-file statuses: ${JSON.stringify(out)}`
  );
  assert.ok(!fs.existsSync(missing), 'missing file stays missing');
  assert.equal(read(gone), JSON.stringify({ mcpServers: { other: 1 } }, null, 2), 'already-gone file untouched');
  const cleaned = read(okToml);
  assert.ok(cleaned.includes('model = "g"'), 'unrelated toml content survives');
  assert.ok(!cleaned.includes(KEY), `aio table fully removed:\n${cleaned}`);
  assert.equal(read(badToml), `[mcp_servers.${KEY}]\ncommand = "x"\n[.note]\n${KEY} must stay visible\n`, 'partial-removal layout untouched');
  assert.deepEqual(
    readLedger().map((e) => path.basename(e.file)),
    ['missing.json', 'bad.toml'],
    'kept entries = missing + unsupported, dropped = removed + already gone'
  );
});

test('removeMcpAdditions: jsonc flat entry removed; nested-object entry kept as unsupported', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'aio-rm-mcp-b-'));
  const okJsonc = write(
    path.join(dir, 'ok.jsonc'),
    `{\n  "mcp": {\n    "${KEY}": { "type": "local", "command": "x" },\n    "other": { "command": "y" }\n  }\n}\n`
  );
  const nestedJsonc = write(
    path.join(dir, 'nested.jsonc'),
    `{\n  "mcp": {\n    "${KEY}": { "nested": { "a": 1 } },\n    "other": { "command": "y" }\n  }\n}\n`
  );
  putLedger([
    { file: okJsonc, key: KEY },
    { file: nestedJsonc, key: KEY },
  ]);

  const out = removeMcpAdditions();

  assert.equal(out[0].status, 'removed');
  assert.equal(out[1].status, 'unsupported layout — manual removal needed, ledger entry kept');
  const cleaned = read(okJsonc);
  assert.ok(!cleaned.includes(KEY), `flat entry gone:\n${cleaned}`);
  assert.ok(cleaned.includes('"other": { "command": "y" }'), 'sibling entry survives');
  assert.ok(cleaned.includes('"mcp"'), 'the mcp block itself survives');
  assert.equal(read(nestedJsonc).split(KEY).length - 1, 1, 'nested layout byte-identical');
  assert.deepEqual(readLedger().map((e) => path.basename(e.file)), ['nested.jsonc'], 'only the unremovable one kept');
});

test('removeMcpAdditions: json key removal — mcpServers root, top-level root, substring-only, parse error', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'aio-rm-mcp-c-'));
  const underRoot = write(
    path.join(dir, 'under-root.json'),
    JSON.stringify({ mcpServers: { [KEY]: { command: 'x' }, other: { command: 'y' } } }, null, 2) + '\n'
  );
  const atRoot = write(path.join(dir, 'at-root.json'), JSON.stringify({ [KEY]: { command: 'x' } }, null, 2) + '\n');
  const substring = write(path.join(dir, 'substring.json'), JSON.stringify({ [KEY + '-v2']: 1 }, null, 2) + '\n');
  const broken = write(path.join(dir, 'broken.json'), `{"${KEY}": broken`);
  putLedger([
    { file: underRoot, key: KEY },
    { file: atRoot, key: KEY },
    { file: substring, key: KEY },
    { file: broken, key: KEY },
  ]);

  const out = removeMcpAdditions();

  assert.deepEqual(
    out.slice(0, 3).map((o) => o.status),
    [
      'removed',
      'removed',
      'unsupported layout — manual removal needed, ledger entry kept',
    ],
    `json matrix: ${JSON.stringify(out)}`
  );
  assert.match(out[3].status, /^parse error — skipped, ledger entry kept \(/, 'parse error carried in the status');
  const a = JSON.parse(read(underRoot));
  assert.equal(KEY in a.mcpServers, false, 'entry deleted from mcpServers');
  assert.ok(a.mcpServers.other, 'sibling entry kept');
  const b = JSON.parse(read(atRoot));
  assert.equal(KEY in b, false, 'top-level entry deleted');
  assert.equal(read(substring), JSON.stringify({ [KEY + '-v2']: 1 }, null, 2) + '\n', 'substring-only file untouched');
  assert.equal(read(broken), `{"${KEY}": broken`, 'malformed file untouched');
  assert.deepEqual(
    readLedger().map((e) => path.basename(e.file)),
    ['substring.json', 'broken.json'],
    'unremovable entries stay in the ledger for a retry'
  );
});
