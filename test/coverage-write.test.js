// the removeMcpAdditions rollback matrix (toml/jsonc/json × removed/kept).
// Isolated: AIO_STATE_DIR → temp (before the src import), every agent home is a
// temp dir behind t.mock.method(os, 'homedir') — never the real user home.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

process.env.AIO_STATE_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'aio-write-cov-')); // must precede the src import

const { genContext, backup, pruneBackups, ensureMcp, removeMcpAdditions, ledgerFile } = await import('../src/write.js');
const { STATE_DIR, BACKUP_DIR } = await import('../src/paths.js');

const KEY = 'codebase-memory-mcp';
const BIN = 'npx -y codebase-memory-mcp';
const LEDGER = path.join(STATE_DIR, 'mcp-ledger.json');

/** Fresh temp home so ensureMcp never reads the real ~/.claude.json & friends. */
function fixtureHome(t) {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'aio-write-home-'));
  t.mock.method(os, 'homedir', () => home);
  t.after(() => fs.rmSync(home, { recursive: true, force: true }));
  return home;
}

function write(p, content) {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
  return p;
}

function read(p) {
  return fs.readFileSync(p, 'utf8');
}

function putLedger(entries) {
  fs.mkdirSync(STATE_DIR, { recursive: true });
  fs.writeFileSync(LEDGER, JSON.stringify(entries, null, 2));
}

function readLedger() {
  return JSON.parse(read(LEDGER));
}

