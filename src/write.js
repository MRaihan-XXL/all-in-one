// write.js — backups, block injection, context manifest, MCP ensure
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import { BACKUP_DIR, STATE_DIR, writeAtomic, preserveCorrupt } from './paths.js';

export const BLOCK_START = '<!-- aio:auto-config:v1:start -->';
export const BLOCK_END = '<!-- aio:auto-config:v1:end -->';
// Detection/match (first block only, no lastIndex state) vs replace-all: a file
// that somehow carries TWO blocks must still collapse to exactly one (6a).
const BLOCK_RE = /<!-- aio:auto-config:v1:start -->[\s\S]*?<!-- aio:auto-config:v1:end -->/;
const BLOCK_RE_G = /<!-- aio:auto-config:v1:start -->[\s\S]*?<!-- aio:auto-config:v1:end -->/g;

export function backup(file, label) {
  if (!fs.existsSync(file)) return null;
  fs.mkdirSync(BACKUP_DIR, { recursive: true });
  const ts = new Date().toISOString().replace(/[:.]/g, '-');
  const safe = String(label).replace(/[^a-z0-9_-]/gi, '_');
  const base = `${safe}__${ts}__${path.basename(file)}`;
  // two backups in the same millisecond must not overwrite each other (CI race)
  let dest = path.join(BACKUP_DIR, base);
  for (let i = 1; fs.existsSync(dest); i++) {
    dest = path.join(BACKUP_DIR, `${safe}__${ts}_${i}__${path.basename(file)}`);
  }
  fs.copyFileSync(file, dest);
  return dest;
}

