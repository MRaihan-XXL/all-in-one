/* ---------------- MCP ensure (FR1) ---------------- */

const LEDGER = path.join(STATE_DIR, 'mcp-ledger.json');
const MCP_KEY = 'codebase-memory-mcp';

function ledgerRead() {
  try {
    return JSON.parse(fs.readFileSync(LEDGER, 'utf8'));
  } catch {
    return [];
  }
}
function ledgerAdd(file, key) {
  const l = ledgerRead();
  if (!l.some((e) => e.file === file && e.key === key)) {
    l.push({ file, key });
    fs.mkdirSync(STATE_DIR, { recursive: true });
    fs.writeFileSync(LEDGER, JSON.stringify(l, null, 2));
  }
}
export function ledgerList() {
  return ledgerRead();
}

/** Drop backups older than `maxAgeDays` so ~/.aio/backups cannot grow forever. */
export function pruneBackups(maxAgeDays = 30) {
  let removed = 0;
  try {
    for (const f of fs.readdirSync(BACKUP_DIR)) {
      const p = path.join(BACKUP_DIR, f);
      try {
        if (Date.now() - fs.statSync(p).mtimeMs > maxAgeDays * 86400000) {
          fs.rmSync(p, { force: true });
          removed++;
        }
      } catch {
        /* locked file — retried next run */
      }
    }
  } catch {
    /* no backup dir yet */
  }
  return removed;
}

export function ensureJsonEntry(file, key, entry, label, rootKey, create = false, { dry = false } = {}) {
  let obj = {};
  if (fs.existsSync(file)) {
    try {
      obj = JSON.parse(fs.readFileSync(file, 'utf8'));
    } catch (e) {
      return { target: path.basename(file), status: `parse error: ${e.message}` };
    }
  } else if (create && fs.existsSync(path.dirname(file))) {
    obj = {}; // agent config dir present → bootstrap the file (gemini settings.json)
  } else {
    return { target: path.basename(file), status: 'file not found — skipped' };
  }
  const holder = rootKey ? (obj[rootKey] ||= {}) : obj;
  if (holder[key]) return { target: path.basename(file), status: 'present' };
  if (dry) return { target: path.basename(file), status: 'would add (dry-run)' };
  backup(file, label);
  holder[key] = entry;
  const text = JSON.stringify(obj, null, 2) + '\n';
  JSON.parse(text); // verify before write
  fs.writeFileSync(file, text);
  ledgerAdd(file, key);
  return { target: path.basename(file), status: 'added' };
}

/** codex config.toml: append [mcp_servers.<key>] only when absent. */
export function ensureTomlEntry(file, key, entry, label, { dry = false } = {}) {
  if (!fs.existsSync(file)) return { target: path.basename(file), status: 'file not found — skipped' };
  const txt = fs.readFileSync(file, 'utf8');
  const header = `[mcp_servers.${key}]`;
  if (txt.includes(header) || txt.includes(`[mcp_servers."${key}"]`)) {
    return { target: path.basename(file), status: 'present' };
  }
  if (dry) return { target: path.basename(file), status: 'would add (dry-run)' };
  backup(file, label);
  const body = Object.entries(entry)
    .map(([k, v]) => `${k} = ${JSON.stringify(v)}`)
    .join('\n');
  fs.writeFileSync(file, txt.replace(/\s*$/, '') + `\n\n${header}\n${body}\n`);
  ledgerAdd(file, key);
  return { target: path.basename(file), status: 'added' };
}

/** opencode.jsonc is JSONC (comments must survive) → textual insert. */
function ensureOpencodeJsonc(key, entry, { dry = false } = {}) {
  const file = path.join(os.homedir(), '.config', 'opencode', 'opencode.jsonc');
  if (!fs.existsSync(file)) return { target: 'opencode.jsonc', status: 'file not found — skipped' };
  const txt = fs.readFileSync(file, 'utf8');
  // key must be an object key ("<key>":), not a random mention of the string
  if (new RegExp(`"${key}"\\s*:`).test(txt)) return { target: 'opencode.jsonc', status: 'present' };
  const markerMatch = txt.match(/"mcp"\s*:\s*\{/); // tolerate spacing/newline variants
  if (!markerMatch) return { target: 'opencode.jsonc', status: 'no "mcp" block — skipped' };
  if (dry) return { target: 'opencode.jsonc', status: 'would add (dry-run)' };
  backup(file, 'opencode-jsonc');
  const idx = markerMatch.index;
  const marker = markerMatch[0];
  const after = txt.slice(idx + marker.length);
  const empty = /^\s*\}/.test(after);
  const insert = `${marker}\n    ${JSON.stringify(key)}: ${JSON.stringify(entry)}${empty ? '' : ','}`;
  const next = txt.slice(0, idx) + insert + after;
  fs.writeFileSync(file, next);
  ledgerAdd(file, key);
  return { target: 'opencode.jsonc', status: 'added' };
}

/** Ensure codebase-memory-mcp exists in opencode / claude / kimi / jcode / codex / gemini configs. */
export function ensureMcp(binary, { dry = false } = {}) {
  const entry = { command: binary };
  const home = os.homedir();
  const results = [];
  results.push(ensureOpencodeJsonc(MCP_KEY, { type: 'local', command: binary }, { dry }));
  results.push(
    ensureJsonEntry(path.join(home, '.claude.json'), MCP_KEY, entry, 'claude-json', 'mcpServers', false, { dry })
  );
  results.push(
    ensureJsonEntry(path.join(home, '.kimi-code', 'mcp.json'), MCP_KEY, entry, 'kimi-mcp', 'mcpServers', false, { dry })
  );
  results.push(
    ensureJsonEntry(path.join(home, '.jcode', 'mcp.json'), MCP_KEY, entry, 'jcode-mcp', 'servers', false, { dry })
  );
  results.push(
    ensureJsonEntry(path.join(home, '.gemini', 'settings.json'), MCP_KEY, entry, 'gemini-settings', 'mcpServers', true, { dry })
  );
  results.push(ensureTomlEntry(path.join(home, '.codex', 'config.toml'), MCP_KEY, entry, 'codex-toml', { dry }));
  return results;
}

/** Reverse exactly what ensureMcp added (recorded in the ledger).
 *  Per-file try/catch: a malformed config is reported, never crashed on, and its
 *  ledger entry is KEPT so rollback can retry after the user fixes the file.
 *  A temporarily missing file is also KEPT (retry when it reappears); a file
 *  whose key is genuinely gone drops out of the ledger. Backups are taken only
 *  when a real modification is about to happen. */
export function removeMcpAdditions() {
  const out = [];
  const keep = [];
  for (const { file, key } of ledgerRead()) {
    if (!fs.existsSync(file)) {
      keep.push({ file, key });
      out.push({ target: path.basename(file), status: 'missing — ledger entry kept for retry' });
      continue;
    }
    const txt = fs.readFileSync(file, 'utf8');
    if (!txt.includes(key)) {
      out.push({ target: path.basename(file), status: 'already gone' });
      continue;
    }
    try {
      if (file.endsWith('.toml')) {
        const esc = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        const re = new RegExp(`\\n?\\[mcp_servers\\."?${esc}"?\\][^\\[]*`, 'g');
        const next = txt.replace(re, '');
        if (next === txt) {
          out.push({ target: path.basename(file), status: 'already gone' });
          continue;
        }
        backup(file, 'rollback-mcp');
        fs.writeFileSync(file, next);
      } else if (file.endsWith('.jsonc')) {
        const re = new RegExp(`${JSON.stringify(key).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*:\\s*\\{[^{}]*\\},?\\s*`, 'g');
        const next = txt.replace(re, '');
        if (next === txt) {
          out.push({ target: path.basename(file), status: 'already gone' });
          continue;
        }
        backup(file, 'rollback-mcp');
        fs.writeFileSync(file, next);
      } else {
        const obj = JSON.parse(txt);
        let removed = false;
        for (const rk of ['mcpServers', 'servers']) {
          if (obj[rk] && typeof obj[rk] === 'object' && key in obj[rk]) {
            delete obj[rk][key];
            removed = true;
            break;
          }
        }
        if (key in obj) {
          delete obj[key];
          removed = true;
        }
        if (!removed) {
          out.push({ target: path.basename(file), status: 'already gone' });
          continue;
        }
        backup(file, 'rollback-mcp');
        fs.writeFileSync(file, JSON.stringify(obj, null, 2) + '\n');
      }
      out.push({ target: path.basename(file), status: 'removed' });
    } catch (e) {
      keep.push({ file, key });
      out.push({ target: path.basename(file), status: `parse error — skipped, ledger entry kept (${String(e.message).slice(0, 60)})` });
    }
  }
  fs.writeFileSync(LEDGER, JSON.stringify(keep, null, 2));
  return out;
}

/* ---------------- stale path repair ---------------- */

const STALE_FROM = 'AI tutorial';
const STALE_TO = 'all-in-one';

/** Repair registry pointers broken by the folder rename. Returns per-file results. dry = report only. */
export function fixPaths(dry = false) {
  const home = os.homedir();
  const targets = [
    path.join(home, 'AGENTS.md'),
    path.join(home, '.claude', 'CLAUDE.md'),
    path.join(home, '.config', 'opencode', 'AGENTS.md'),
    path.join(home, '.kimi-code', 'AGENTS.md'),
    path.join(home, '.jcode', 'AGENTS.md'),
    path.join(home, '.codex', 'AGENTS.md'),
    path.join(home, '.gemini', 'GEMINI.md'),
  ];
  const results = [];
  for (const file of targets) {
    if (!fs.existsSync(file)) continue;
    const txt = fs.readFileSync(file, 'utf8');
    if (!txt.includes(STALE_FROM)) continue;
    const count = txt.split(STALE_FROM).length - 1;
    if (dry) {
      results.push({ target: file, status: `would repair ${count} path reference(s) (dry-run)` });
      continue;
    }
    backup(file, 'pathfix');
    fs.writeFileSync(file, txt.split(STALE_FROM).join(STALE_TO));
    results.push({ target: file, status: `repaired ${count} path reference(s)` });
  }
  return results;
}
