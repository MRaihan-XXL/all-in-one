// write.js — backups, block injection, context manifest, MCP ensure, path repair
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { BACKUP_DIR, STATE_DIR } from './paths.js';

export const BLOCK_START = '<!-- aio:auto-config:v1:start -->';
export const BLOCK_END = '<!-- aio:auto-config:v1:end -->';
const BLOCK_RE = /<!-- aio:auto-config:v1:start -->[\s\S]*?<!-- aio:auto-config:v1:end -->/;

export function backup(file, label) {
  if (!fs.existsSync(file)) return null;
  fs.mkdirSync(BACKUP_DIR, { recursive: true });
  const ts = new Date().toISOString().replace(/[:.]/g, '-');
  const safe = String(label).replace(/[^a-z0-9_-]/gi, '_');
  const dest = path.join(BACKUP_DIR, `${safe}__${ts}__${path.basename(file)}`);
  fs.copyFileSync(file, dest);
  return dest;
}

